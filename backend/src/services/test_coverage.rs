    // ── Macro Expansion & Synthetic Span Resolution Tests ─────────────────────

    #[test]
    fn test_macro_expansion_contractimpl_resolution() {
        let mut source_map = CoverageSourceMap::new();

        let contract_file = "contracts/token/src/lib.rs";
        let total_lines = 50;

        // Register #[contractimpl] macro spanning lines 15 to 30 with synthetic instructions 500..=550
        let expansion = MacroExpansionSpan::contractimpl(contract_file, 15, 30, (500, 550));
        source_map.add_macro_expansion(expansion);

        // Simulated test execution instructions generated by the macro
        let executed_instructions = vec![502, 510, 545];
        let raw_lines = vec![5, 6, 7]; // ordinary non-macro lines

        let result = source_map.resolve_coverage(
            contract_file,
            total_lines,
            &raw_lines,
            &executed_instructions,
        );

        // Verify that methods inside #[contractimpl] (lines 15..=30) were marked as covered
        assert!(result.covered_lines.contains(&15));
        assert!(result.covered_lines.contains(&30));
        assert!(result.covered_lines.contains(&5));

        // Total covered lines: 3 from raw + 16 from contractimpl = 19
        assert_eq!(result.covered_lines_count, 19);
        assert!((result.coverage_percent - 38.0).abs() < f64::EPSILON);
    }

    #[test]
    fn test_synthetic_lines_remapping_to_macro_invocation() {
        let mut source_map = CoverageSourceMap::new();
        let contract_file = "contracts/vault/src/lib.rs";

        let mut expansion = MacroExpansionSpan::contractimpl(contract_file, 10, 20, (100, 200));
        // Synthetic lines emitted by macro expansion
        expansion.synthetic_lines = vec![9991, 9992];
        source_map.add_macro_expansion(expansion);

        // When test execution hits synthetic line 9991
        let raw_lines = vec![9991];
        let executed_instructions = vec![];

        let result = source_map.resolve_coverage(
            contract_file,
            50,
            &raw_lines,
            &executed_instructions,
        );

        // Should be remapped to the macro invocation line (10)
        assert!(result.covered_lines.contains(&10));
        assert!(!result.covered_lines.contains(&9991));
        assert_eq!(result.covered_lines_count, 1);
    }

    #[test]
    fn test_direct_instruction_source_mapping() {
        let mut source_map = CoverageSourceMap::new();
        let file = "contracts/common/src/util.rs";

        source_map.add_instruction_mapping(10, file.to_string(), 4);
        source_map.add_instruction_mapping(20, file.to_string(), 8);

        let result = source_map.resolve_coverage(file, 20, &[], &[10, 20]);
        assert_eq!(result.covered_lines, vec![4, 8]);
        assert_eq!(result.covered_lines_count, 2);
        assert!((result.coverage_percent - 10.0).abs() < f64::EPSILON);
    }
