// ── Macro Expansion Tracking & Synthetic Span Mapping ──────────────────────

/// Source code location span in a contract file.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct SourceSpan {
    pub file: String,
    pub start_line: usize,
    pub end_line: usize,
}

/// Type of procedural macro generating synthetic code.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub enum MacroType {
    /// Soroban/Stellar #[contractimpl] macro
    ContractImpl,
    /// #[contracttype] macro
    ContractType,
    /// #[contracterror] macro
    ContractError,
    /// Custom procedural macro
    Custom(String),
}

/// Represents a synthetic code region generated by macro expansion mapped back to original source code.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct MacroExpansionSpan {
    pub macro_type: MacroType,
    /// Primary location in original source code where macro was invoked
    pub invocation_span: SourceSpan,
    /// Range of synthetic bytecode instruction counters [start_offset, end_offset]
    pub synthetic_instruction_range: (u32, u32),
    /// Synthetic line numbers generated during macro expansion
    pub synthetic_lines: Vec<usize>,
    /// Source lines covered by this macro implementation (e.g. methods inside #[contractimpl])
    pub mapped_source_lines: Vec<usize>,
}

impl MacroExpansionSpan {
    /// Create a new macro expansion mapping for #[contractimpl]
    pub fn contractimpl(
        file: impl Into<String>,
        start_line: usize,
        end_line: usize,
        instruction_range: (u32, u32),
    ) -> Self {
        let mapped_source_lines: Vec<usize> = (start_line..=end_line).collect();
        Self {
            macro_type: MacroType::ContractImpl,
            invocation_span: SourceSpan {
                file: file.into(),
                start_line,
                end_line,
            },
            synthetic_instruction_range: instruction_range,
            synthetic_lines: Vec::new(),
            mapped_source_lines,
        }
    }
}

/// Resolved coverage calculation result for a source file.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct CoverageResolutionResult {
    pub file: String,
    pub total_lines: usize,
    pub covered_lines_count: usize,
    pub covered_lines: Vec<usize>,
    pub coverage_percent: f64,
}

/// Source map for resolving execution instruction counters and macro synthetic spans back to source lines.
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct CoverageSourceMap {
    /// Registered macro expansion synthetic spans
    pub macro_expansions: Vec<MacroExpansionSpan>,
    /// Map of bytecode instruction offset -> (file, line)
    pub instruction_to_source: std::collections::BTreeMap<u32, (String, usize)>,
}

impl CoverageSourceMap {
    pub fn new() -> Self {
        Self::default()
    }

    /// Register a macro expansion span in the source map
    pub fn add_macro_expansion(&mut self, expansion: MacroExpansionSpan) {
        self.macro_expansions.push(expansion);
    }

    /// Add an explicit instruction offset to source line mapping
    pub fn add_instruction_mapping(&mut self, offset: u32, file: String, line: usize) {
        self.instruction_to_source.insert(offset, (file, line));
    }

    /// Resolve an instruction counter offset back to its source location, taking into account
    /// macro expansions and synthetic spans.
    pub fn resolve_instruction(&self, offset: u32) -> Option<(String, usize)> {
        // First check explicit instruction mapping
        if let Some((file, line)) = self.instruction_to_source.get(&offset) {
            // Check if mapped line falls into a synthetic macro expansion
            for expansion in &self.macro_expansions {
                if expansion.synthetic_lines.contains(line) {
                    return Some((
                        expansion.invocation_span.file.clone(),
                        expansion.invocation_span.start_line,
                    ));
                }
            }
            return Some((file.clone(), *line));
        }

        // Check if instruction offset falls into a macro expansion synthetic instruction range
        for expansion in &self.macro_expansions {
            let (start, end) = expansion.synthetic_instruction_range;
            if offset >= start && offset <= end {
                return Some((
                    expansion.invocation_span.file.clone(),
                    expansion.invocation_span.start_line,
                ));
            }
        }

        None
    }

    /// Resolve raw line hits and instruction hits into mapped source line coverage.
    pub fn resolve_coverage(
        &self,
        file: &str,
        total_lines: usize,
        raw_covered_lines: &[usize],
        executed_instruction_offsets: &[u32],
    ) -> CoverageResolutionResult {
        let mut covered_set = std::collections::BTreeSet::new();

        // 1. Process raw covered lines, checking for synthetic line remaps
        for &line in raw_covered_lines {
            let mut mapped = false;
            for expansion in &self.macro_expansions {
                if expansion.invocation_span.file == file {
                    if expansion.synthetic_lines.contains(&line) {
                        covered_set.insert(expansion.invocation_span.start_line);
                        mapped = true;
                    }
                }
            }
            if !mapped && line <= total_lines {
                covered_set.insert(line);
            }
        }

        // 2. Process executed instructions
        for &offset in executed_instruction_offsets {
            if let Some((target_file, target_line)) = self.resolve_instruction(offset) {
                if target_file == file && target_line <= total_lines {
                    covered_set.insert(target_line);
                }
            }

            // Also check if any macro expansion is triggered by this instruction
            for expansion in &self.macro_expansions {
                let (start, end) = expansion.synthetic_instruction_range;
                if offset >= start && offset <= end && expansion.invocation_span.file == file {
                    // Mark all mapped source lines (e.g. functions inside #[contractimpl]) as covered
                    for &line in &expansion.mapped_source_lines {
                        if line <= total_lines {
                            covered_set.insert(line);
                        }
                    }
                }
            }
        }

        let covered_lines: Vec<usize> = covered_set.into_iter().collect();
        let coverage_percent = if total_lines == 0 {
            0.0
        } else {
            ((covered_lines.len() as f64 / total_lines as f64) * 100.0).clamp(0.0, 100.0)
        };

        CoverageResolutionResult {
            file: file.to_string(),
            total_lines,
            covered_lines_count: covered_lines.len(),
            covered_lines,
            coverage_percent,
        }
    }
}

// ── Service ───────────────────────────────────────────────────────────────────

#[derive(Clone)]
pub struct TestCoverageService {
    db: PgPool,
    redis: redis::Client,
}

impl TestCoverageService {
    pub fn new(db: PgPool, redis: redis::Client) -> Self {
        Self { db, redis }
    }

    /// Persist a new coverage snapshot and update the Redis cache.
    #[instrument(skip(self, data), fields(project = %data.project_name, branch = %data.branch))]
    pub async fn submit_coverage(
        &self,
        data: NewTestCoverage,
    ) -> Result<TestCoverage, CoverageError> {
        validate_coverage(&data)?;

        info!("Persisting coverage report");

        let record = sqlx::query_as::<_, TestCoverage>(
            "INSERT INTO test_coverage \
             (id, project_name, branch, commit_sha, coverage_percent, total_lines, covered_lines, created_at) \
             VALUES ($1, $2, $3, $4, $5, $6, $7, $8) \
             RETURNING *",
        )
        .bind(Uuid::new_v4())
        .bind(&data.project_name)
        .bind(&data.branch)
        .bind(&data.commit_sha)
        .bind(data.coverage_percent)
        .bind(data.total_lines)
        .bind(data.covered_lines)
        .bind(Utc::now())
        .fetch_one(&self.db)
        .await?;

        self.cache_set(&data.project_name, &record).await?;
        Ok(record)
    }

    /// Resolve coverage using macro expansion tracking & synthetic span mapping, then persist
    #[instrument(skip(self, source_map), fields(project = %project_name, branch = %branch))]
    pub async fn submit_coverage_with_source_map(
        &self,
        project_name: &str,
        branch: &str,
        commit_sha: &str,
        file: &str,
        total_lines: usize,
        raw_lines: &[usize],
        executed_instructions: &[u32],
        source_map: &CoverageSourceMap,
    ) -> Result<TestCoverage, CoverageError> {
        let resolved = source_map.resolve_coverage(file, total_lines, raw_lines, executed_instructions);
        let data = NewTestCoverage {
            project_name: project_name.to_string(),
            branch: branch.to_string(),
            commit_sha: commit_sha.to_string(),
            coverage_percent: resolved.coverage_percent,
            total_lines: resolved.total_lines as i32,
            covered_lines: resolved.covered_lines_count as i32,
        };
        self.submit_coverage(data).await
    }

    /// Return the most-recent coverage snapshot for a project (cache-first).
    #[instrument(skip(self), fields(project = %project_name))]
    pub async fn get_latest_coverage(
        &self,
        project_name: &str,
    ) -> Result<TestCoverage, CoverageError> {
        // 1. Try Redis cache.
        if let Some(cached) = self.cache_get(project_name).await? {
            debug!("Coverage cache hit");
            return Ok(cached);
        }

        // 2. Fall back to DB.
        debug!("Coverage cache miss – querying database");
        let record = sqlx::query_as::<_, TestCoverage>(
            "SELECT * FROM test_coverage \
             WHERE project_name = $1 \
             ORDER BY created_at DESC LIMIT 1",
        )
        .bind(project_name)
        .fetch_optional(&self.db)
        .await?
        .ok_or_else(|| CoverageError::NotFound(project_name.to_string()))?;

        self.cache_set(project_name, &record).await?;
        Ok(record)
    }

    // ── helpers ───────────────────────────────────────────────────────────────

    fn cache_key(project_name: &str) -> String {
        format!("coverage:latest:{project_name}")
    }

    async fn cache_get(&self, project_name: &str) -> Result<Option<TestCoverage>, CoverageError> {
        let mut conn = self.redis.get_multiplexed_async_connection().await?;
        let raw: Option<String> = conn.get(Self::cache_key(project_name)).await?;
        raw.map(|s| serde_json::from_str(&s).map_err(CoverageError::from))
            .transpose()
    }

    async fn cache_set(
        &self,
        project_name: &str,
        record: &TestCoverage,
    ) -> Result<(), CoverageError> {
        let serialized = serde_json::to_string(record)?;
        let mut conn = self.redis.get_multiplexed_async_connection().await?;
        let _: () = conn
            .set_ex(Self::cache_key(project_name), serialized, 3600)
            .await?;
        debug!("Updated coverage cache for {project_name}");
        Ok(())
    }
}

// ── Validation ────────────────────────────────────────────────────────────────

fn validate_coverage(data: &NewTestCoverage) -> Result<(), CoverageError> {
    if data.project_name.trim().is_empty() {
        return Err(CoverageError::Validation(
            "projectName is required".to_string(),
        ));
    }
    if data.branch.trim().is_empty() {
        return Err(CoverageError::Validation("branch is required".to_string()));
    }
    if data.commit_sha.trim().is_empty() {
        return Err(CoverageError::Validation(
            "commitSha is required".to_string(),
        ));
    }
    if !(0.0..=100.0).contains(&data.coverage_percent) {
        return Err(CoverageError::Validation(
            "coveragePercent must be between 0 and 100".to_string(),
        ));
    }
    if data.total_lines < 0 {
        return Err(CoverageError::Validation(
            "totalLines must be non-negative".to_string(),
        ));
    }
    if data.covered_lines < 0 {
        return Err(CoverageError::Validation(
            "coveredLines must be non-negative".to_string(),
        ));
    }
    if data.covered_lines > data.total_lines {
        return Err(CoverageError::Validation(
            "coveredLines cannot exceed totalLines".to_string(),
        ));
    }
    Ok(())
}

